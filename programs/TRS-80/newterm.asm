;	TITLE	NEWTERM - TRS-80 CP/M TERMINAL EMULATOR    08/06/81
;
;	TERMINAL EMULATOR PROGRAM FOR TRS-80 CP/M V 1.4 WITH
;		STANDARD UART RS-232 PORT
;			STEVEN GOLDBERG
;			AUGUST, 1981
;
;
KBCHAR	EQU	0049H			;KB POLL, WAITS FOR KEY
BDOS	EQU	4205H			;BIOS ENTRYPOINT CALL
RESPRT	EQU	0E8H			;OUT TO E8 FOR RESET
BRGEN	EQU	0E9H			;BAUD-RATE GENERATOR
USTAT	EQU	0EAH			;UART STATUS
XMIT	EQU	0EBH			;UART XMIT BYTE
RECV	EQU	0EBH			;UART RECV BYTE
KBREDY	EQU	0BH			;KEYBOARD READY INDIC.
LPRINT	EQU	05H			;CP/M BIOS PRINTER OUT
KBPOLL	EQU	002BH			;KEYBOARD POLL ROUTINE
CONOUT	EQU	0033H			;CONSOLE OUTPUT
CLS	EQU	01C9H			;ROM CLEAR SCREEN
TABLEN	EQU	07			;CHRTBL LENGTH=6
NUMMAC	EQU	03			;MACRO TABLE LENGTH=3
BRTABL	EQU	0BB74H		;CP/M BAUD RATE TABLE
;
;.........BEGIN TERMINAL EMULATOR
;
TERMNL:	CALL	CLS			;CLEAR SCREEN
	LD	HL,DUPLEX		;SET DUP TO LOCAL COPY
	LD	(HL),00H		;0=LOCAL COPY, 1=NONE
	LD	A,00H			;CLEAR OUT UART CONFIGS
	OUT	(RESPRT),A		;BY OUTPUT TO PORT 0E8
;
;.........SET UP UART SWITCHES ACCORDING TO SENSES
;
;         GET SENSE SWITCH VALUES
;
	IN	A,(0E9H)		;GET VALUE OF SWITCHES
	AND	0F8H			;MASK OUT BAUD RATE
	OR	04			;CLEAR XMIT BREAK MODE
	OUT	(USTAT),A			;CONFIGURE PORT
	IN	A,(0E9H)		;GET SWITCHES AGAIN
	AND	07H			;GET BAUD RATE
	LD	HL,BRTABL		;PT TO BAUD RATE TABLE
	LD	B,00			;CLEAR B-REG FOR BC
	LD	C,A			;BAUD RATE=BC
	ADD	HL,BC			;POINT TO LOC IN TABLE
	LD	A,(HL)			;GET VALUE FOR DIVISOR
	OUT	(BRGEN),A		;GENERATE BAUD RATE
;
;.........BEGIN MAIN LOOP (SCAN, SEND, READ)
;
SCAN:	CALL	KBPOLL			;CHECK FOR BYTE
	OR	A			;SET FLAGS
	JP	Z,RCVTST		;NO DATA - CHECK RECV
;
;.........BEFORE SENDING, EXAMINE DATA FOR SPECIAL CHARACTERS
;
	CP	1FH			;CLEAR KEY?
	JR	Z,CLRSEQ		;YES - PROCESS COMMAND
;
;.........DO BLOCK COMPARE TO CONVERT SPECIAL KEYS
;
;	  COMPARE TABLE IS CALLED 'CHRTBL'
;		(DATA IS ARRANGED :   OLDCHAR,NEWCHAR, ETC..)
;
;
	LD	HL,CHRTBL		;GET LOCATION OF TABLE
	LD	BC,TABLEN		;GET LENGTH OF TABLE
CPLOOP:	CPI				;SEARCH TABLE, ODD VALS
	JR	Z,NEWCHR		;SET NEW CHARACTER
	PUSH	AF			;SAVE BYTE
	LD	A,C			;IS IT END YET?
	CP	00H			;(BC=0000?)
	JP	Z,MACROS		;YES - NEXT SERIES
	POP	AF			;NO - CONTINUE
	INC	HL			;(SKIP EVEN DATA)
	JR	CPLOOP			;CONTINUE SEARCH
NEWCHR:	LD	A,(HL)			;GET ASSOCIATED CHAR.
	JP	XMTCHR			;TRANSMIT BYTE
CLRSEQ:	;SECTION TO PROCESS COMMANDS TO THE EMULATOR PROGRAM
	CALL	KBCHAR			;GET BYTE FROM CONSOLE
	CP	1FH			;IS IT A CLEAR?
	JR	NZ,BRKCHK		;NO - CHECK FOR BRK
	CALL	CLS			;CLEAR SCREEN (ROM RTN)
	JP	RCVTST				;CONTINUE PROCESSING
;
;.........IF KEY STRUCK WAS 'BREAK', THEN RESET CP/M SYSTEM
;
BRKCHK:	CP	01			;BREAK?
	JR	NZ,ENTCHK		;SEE IF 'ENTER'..
	LD	C,00			;REBOOT
	CALL	BDOS			;GO TO 'A>'
;
;.........IF KEY STRUCK WAS 'ENTER', THEN TOGGLE DUPLEX SWITCH
;
ENTCHK:	CP	0DH			;CR?
	JP	NZ,PRTTST		;NO - PRINT?
	LD	A,(DUPLEX)		;GET CURRENT STATUS
	CP	00H			;CURRENTLY LOCAL COPY?
	JR	NZ,LCLDUP		;NO - SET LOCAL COPY
	LD	A,01H			;ELSE RESET LOCAL COPY
SAVDUP:	LD	(DUPLEX),A		;SAVE DUPLEX SWITCH
	JP	RCVTST				;CONTINUE MAIN PROG
LCLDUP:	LD	A,00H			;SET LOCAL COPY MODE
	JR	SAVDUP			;SAVE DUPLEX SWITCH
PRTTST:	CP	'P'			;HIT A CLR-P?
	JR	NZ,RPTTST		;NO - IGNORE OTHERS
	LD	A,(PRINTR)		;TOGGLE PRINTER SWITCH
	OR	A			;SET FLAGS
	CP	00H			;OFF?
	JR	Z,SETPRT		;YES - SET PRINTER ON
	LD	A,00H			;NO - SET PRINTER OFF
SAVPRT:	LD	(PRINTR),A		;AND SAVE PRINTER STAT
	JP	RCVTST			;SKIP TO RECEIVE TEST
SETPRT:	LD	A,0FFH			;SET PRINTER TO ACTIVE
	JR	SAVPRT			;SAVE PRINTER STATUS
RPTTST:	CP	'R'			;R? (REPEAT GROUP)
	JP	NZ,RCVTST		;NO - IGNORE OTHERS
	LD	A,0BFH			;PUT FLAG ON SCREEN
	LD	(3C3FH),A		;AT TOP (3C3FH)
	CALL	0049H			;GET A CHARACTER
RPLOOP:	CALL	SEND			;SEND IT THRU UART XMIT
	LD	A,(SAVE)		;GET BYTE AGAIN
	CALL	0033H			;PRINT IT
	CALL	002BH			;CHECK FOR INTERRUPT
	OR	A			;SET FLAGS
	JR	Z,RPAUSE		;NO INTERRUPT - CONT.
	CP	1FH			;CLR? (INTERRUPT=CLEAR)
	JR	Z,CLRRPT		;YES - STOP SENDING
RPAUSE:	IN	A,(0EAH)		;CHECK FOR XMIT RDY
	BIT	6,A			;READY?
	JR	Z,RPAUSE		;NO - PAUSE
	LD	A,(SAVE)		;RESTORE BYTE
	JR	RPLOOP			;AND KEEP XMITTING
CLRRPT:	LD	A,20H			;CLEAR MARK ON SCREEN
	LD	(3C3FH),A		;BY PUTTING SPACE THERE
	JP	RCVTST			;CHECK FOR INPUT BYTE
CHRTBL:	DEFB	01,03,5BH,5BH,18H,5EH,19H,5DH,1AH,00,0AH,18H
MACROS:	;	SECTION TO PERFORM KEYBOARD MACROS FROM
;		DATA STORED IN MACRO TABLE AT 'MACTBL' ARRANGED
;		IN ORDER: KEY, ADDR OF MACRO, LEN OF MACRO.
;
	POP	AF			;RESTORE BYTE
	LD	HL,MACTBL		;GET LOCATION OF TABLE
	LD	BC,NUMMAC		;GET NUMBER OF MACROS
;
;.........SEARCH THROUGH MACTBL EVERY FOURTH DATA ELEMENT
;	  FOR KEY STRUCK.
;
MACLOC:	CPI				;SEARCH FOR A-REG
	JR	Z,MACFND		;FOUND - GET DATA
	PUSH	AF			;SAVE BYTE
	LD	A,C			;IS IT NO FIND?
	CP	00H			;(BC=0000)?
	JR	Z,COSMIC			;CONTINUE IF NOT
	POP	AF			;RESTORE BYTE
	INC	HL			;SKIP NEXT 3 POSNS
	INC	HL
	INC	HL
	JR	MACLOC			;CONTINUE SEARCH..
COSMIC:	POP	AF			;RESTORE CHARACTER
	JR	XMTCHR			;TRANSMIT CHARACTER
MACFND:	;	MACRO FOUND - GET ADDRESS OF THE MACRO
	LD	E,(HL)			;GET LOB OF ADDR
	INC	HL			;POINT TO NEXT BYTE
	LD	D,(HL)			;GET HOB OF ADDR
;
;.........ADDRESS OF MACRO IS IN DE REGISTER PAIR
;
	INC	HL			;POINT TO LENGTH BYTE
	LD	B,(HL)			;GET LENGTH OF MACRO
;
;.........LENGTH OF MACRO IS IN B REGISTER FOR DJNZ COMMAND
;
XMLOOP:	LD	A,(DE)			;GET BYTE IN MACRO
	INC	DE			;POINT TO NEXT ONE
	LD	C,A			;SAVE CHARACTER
	LD	A,(DUPLEX)		;CHECK FOR LOCAL COPY
	OR	A			;SET FLAGS
	JR	NZ,SKIP2		;SKIP OVER IF NOT SET
	LD	A,C			;RESTORE BYTE
	PUSH	AF			;SAVE ALL REGS
	PUSH	BC			;ALL OF EM
	PUSH	DE			;LILAF
	PUSH	HL
	CALL	CONOUT			;PRINT TO CRT
	POP	HL
	POP	DE
	POP	BC
	POP	AF
SKIP2:	LD	A,C			;RESTORE A-REG AGAIN
	PUSH	DE			;SAVE OUR POINTER!
	CALL	SEND			;SEND BYTE IN A TO PORT
	POP	DE			;AND RESTORE IT.
PAUSE:	IN	A,(0EAH)		;STILL XMITTING?
	BIT	6,A			;TEST BIT 6 FOR WAIT
	JR	Z,PAUSE			;IF SO - WAIT
	DJNZ	XMLOOP			;UNTIL END OF MACRO
	JP	RCVTST				;CONTINUE PROCESSING
;
;.........SECTION TO TRANSMIT A CHARACTER THROUGH MODEM
;	  WHILE CHECKING STATUS BEFORE SENDING
;
SEND:	LD	(SAVE),A		;SAVE BYTE
;
;.........ASSUMING THAT PORT IS READY FOR OUTPUT, SEND BYTE
;
	LD	A,(SAVE)		;RESTORE BYTE
	OUT	(XMIT),A			;OUTPUT BYTE TO UART
	LD	E,A			;SAVE BYTE
	LD	A,(PRINTR)		;PRINTER ASSIGNED?
	OR	A			;SET FLAGS.
	RET	Z			;NO - RETURN
	LD	C,LPRINT		;YES - PRINT CHAR.
	CALL	BDOS			;DO IT.
	RET				;BACK TO CALLER
XMTCHR:	LD	(SAVE),A		;SAVE A-REG
	LD	A,(DUPLEX)		;FIND DUPLEX STATUS
	OR	A			;SET FLAGS
	JR	NZ,SKPOVR		;SKIP PRINT IF DUP=1
	LD	A,(SAVE)		;RESTORE BYTE
	CP	1BH			;ESC? - SKIPOVER
	JR	Z,SKPOVR		;YES - DO NOT PRINT
	CP	18H			;CTL-X?
	JR	Z,SKPOVR		;YES - SKIP OVER
	CP	5EH			;??
		LD	E,A			;PREPARE TO OUTPUT
	LD	C,02		;PRINT BYTE
	CALL	BDOS			;USING CP/M ROUTINE
SKPOVR:	LD	A,(SAVE)		;GET BYTE INTO ACCUM
	CP	00H			;IS IT NULL?
	JR	Z,RCVTST		;YES - IGNORE IT
	CALL	SEND			;SEND THE BYTE
	JR	RCVTST			;AND CHECK FOR LINE
RCVTST:		;TEST FOR DATA RECEIVE FROM UART PORT
	IN	A,(USTAT)		;CHECK FOR RECV READY
	BIT	7,A			;BIT 7=REC'V READY
	JP	Z,SCAN			;NOT READY - GO TO MAIN
					;	     SCAN.
	IN	A,(RECV)		;GET DATA FROM PORT
	AND	7FH			;CLEAR PARITY BIT
;
;.........DISREGARD IF THE BYTES IS A LINE-FEED
;
	CP	0AH			;LF?
	JP	Z,SCAN			;YES - RESCAN
	LD	E,A			;PUT IN E-REG
	CALL	CONOUT			;PRINT CHARACTER
	LD	A,(PRINTR)		;IS PRINTER ASSIGNED?
	OR	A			;SET FLAGS.
	JP	Z,SCAN			;NO PRINTER - NEXT.
	LD	C,LPRINT		;SET BIOS CMD TO PRINT
	CALL	BDOS			;PRINT TO LIST DEVICE
;
;.........GO BACK TO BEGINNING OF SCAN LOOP
;
	JP	SCAN			;PLAY TERMINAL...
;
;
;**************************************************************
;*							      *
;*		DATA STORAGE AREA AND ASSIGNMENTS	      *
;*							      *
;**************************************************************
;
;
SAVE:	DEFB	00				;A-REG STORAGE
DUPLEX:	DEFB	00				;DUPLEX SAVE
PRINTR:	DEFB	00				;PRINTER STATUS
MACTBL:	DEFB	6BH				;'SHIFT-K'
	DEFW	MACRO1				;PTR TO MACRO1
	DEFB	24			;LENGTH OF MACRO1
	DEFB	6CH				;'SHIFT-L'
	DEFW	MACRO2				;PTR TO MACRO2
	DEFB	17
	DEFB	67H				;'SHIFT-G'
	DEFW	MACRO3
	DEFB	21
;
;.........MACRO STORAGE AREA
;
MACRO1:	DEFB	'FP400FT20PT20FT20PT9FT8',0DH	;MUL KILL FUNC
MACRO2:	DEFB	',UG656JP,CSCN360',0DH		;LOG IN MACRO
MACRO3:	DEFB	'G,PROCFIL/UN=MUBRAT1',0DH	;GET
