*	XMET - A CROSS ASSEMBLER FOR THE HEATH ET-18 AND
*	ET-3400.  THE OUTPUT OF THIS CROSS ASSEMBLER
*	IS A LIST OF "DB" STATEMENTS THAT MAY BE ASSEMBLED
*	WITH AN 8080 ASSEMBLER.

*	TO USE THIS CROSS ASSEMBLER, ENTER

*	A>XMET d:FILENAME.TYP [d:]

*	WHERE d: IS A DRIVE DESIGNATION, AND [d:] IS AN
*	OPTIONAL OUTPUT DRIVE (IF DIFFERENT FROM THE INPUT
*	DRIVE

*	BY P. SWAYNE, HUG  17-MAR-83

*	DEFINITIONS

HDOS	EQU	0		;ASSEMBLE FOR HDOS
CPM	EQU	1		;ASSEMBLE FOR CP/M

	IF	HDOS
.EXIT	EQU	0		;EXIT TO HDOS
.SCIN	EQU	1		;SINGLE CHARACTER INPUT
.SCOUT	EQU	2		;SINGLE CHARACTER OUTPUT
.READ	EQU	4		;READ FROM DEVICE
.WRITE	EQU	5		;WRITE TO DEVICE
.CONSL	EQU	6		;SET CONSOLE OPERATIONS
.CTLC	EQU	41Q		;SET CONTROL-C VECTOR
.OPENR	EQU	42Q		;OPEN FOR READ
.OPENW	EQU	43Q		;OPEN FOR WRITE
.CLOSE	EQU	46Q		;CLOSE
.SETTP	EQU	52Q		;SET MEMORY TOP
.ERROR	EQU	57Q		;REPORT ERROR
.LOADD	EQU	62Q		;LOAD DEVICE DRIVER
CPHD	EQU	188EH		;COMPARE HL AND DE
TYPTX	EQU	195EH		;TYPE TEXT AFTER CALL
ZERO	EQU	198AH		;ZERO AN AREA OF MEMORY
	ORG	2280H
	ENDIF
	IF	CPM
BDOS	EQU	4205h		;BDOS JUMP VECTOR
FCB	EQU	425CH		;FILE CONTROL BLOCK
FCB2	EQU	426CH		;SECOND FCB
CONIN	EQU	1		;CONSOLE INPUT
CONOUT	EQU	2		;CONSOLE OUTPUT
LSTOUT	EQU	5		;LST OUTPUT
DCIO	EQU	6		;DIRECT CONSOLE I/O
OPENF	EQU	15		;OPEN FILE
CLOSEF	EQU	16		;CLOSE FILE
DELETF	EQU	19		;DELETE FILE
READF	EQU	20		;READ FILE (SEQUENTIAL)
WRITEF	EQU	21		;WRITE FILE (SEQ)
MAKEF	EQU	22		;MAKE FILE
SETDMA	EQU	26		;SET DMA ADDRESS
	ORG	4300H
	ENDIF


*	GET ARGUMENT AND OPEN FILES

START	DS	0
	IF	CPM
	LXI	H,0
	DAD	SP		;FIND STACK
	SHLD	OLDSP		;SAVE IT
	LXI	SP,4300H		;SET NEW ONE
	ENDIF
	CALL	TYPTX
	DB	13,10,'XMET ET-18 and ET-3400 M6800 Cross Assembler'
	DB	', V 1.0',13,10+80H
	IF	HDOS
	LXI	H,RDBUFE
	SCALL	.SETTP		;FIND MEMORY TOP
	JC	ERROR		;SHOULD NOT HAPPEN
	LXI	H,EXIT
	MVI	A,3
	SCALL	.CTLC		;SET UP CONTROL-C EXIT
	LXI	H,0
	DAD	SP		;FIND STACK LOCATION
	MOV	A,L		;GET LOW BYTE
	CPI	80H		;AT NORMAL LOCATION?
	JZ	NOFILE		;YES, NO FILE GIVEN
SOB	MOV	A,M		;GET A CHARACTER
	CPI	' '		;SPACE?
	INX	H
	JZ	SOB		;SKIP SPACES
	DCX	H		;REMOVE LAST INX
	PUSH	H		;SAVE FILE NAME ADDRESS
	LXI	D,INDEF		;ELSE, POINT TO DEFAULTS
	XRA	A		;USE CHANNEL 0
	SCALL	.OPENR		;OPEN FOR READ
	JC	ERROR		;COULDN'T FIND FILE
	POP	H		;GET NAME ADDRESS
	PUSH	H		;SAVE AGAIN
FB	MOV	A,M		;SEARCH FOR TRAILING BLANK
	CPI	' '		;SPACE?
	JZ	GOTDRV		;YES, GOT OUTPUT DRIVE
	ORA	A		;END
	JZ	NODRV		;YES, NO DRIVE
	INX	H
	JMP	FB		;LOOK TILL END
GOTDRV	INX	H		;SKIP BLANK
	MOV	A,M
	CPI	' '		;AND ANY OTHER ONES
	JZ	GOTDRV
	LXI	D,OUTDEF	;POINT TO OUTPUT DEFAULT
	MVI	B,3		;SET A COUNTER
MOVDEF	STAX	D		;MOVE DEVICE
	INX	H
	INX	D
	MOV	A,M
	DCR	B
	JNZ	MOVDEF
NODRV	POP	H		;RESTORE FILE NAME ADDRESS
	PUSH	H		;SAVE AGAIN
FCOL	MOV	A,M		;FIND COLON AFTER DRIVE
	ORA	A		;END, NO COLON
	JZ	NOCOL
	CPI	' '
	JZ	NOCOL		;SPACE, NO COLON
	CPI	':'
	JZ	GOTCOL		;GOT ONE
	INX	H
	JMP	FCOL
GOTCOL	POP	D		;DUMP OLD FNAME ADDR
	INX	H		;SKIP COLON
	PUSH	H		;SAVE NEW FNAME ADDR
NOCOL	POP	H		;RESTORE FILE NAME ADDRESS
	PUSH	H		;SAVE AGAIN
FPER	MOV	A,M		;FIND PERIOD AFTER FNAME
	ORA	A		;END, NO PERIOD
	JZ	NOPER
	CPI	'.'
	JZ	GOTPER		;GOT ONE
	INX	H
	JMP	FPER
GOTPER	MVI	M,0		;ZERO OUT PERIOD
NOPER	POP	H		;RESTORE FNAME ADDRESS
	LXI	D,OUTDEF
	MVI	A,1
	SCALL	.OPENW		;TRY TO OPEN OUTPUT
	JC	ERROR		;COULDN'T DO IT
	MVI	B,0
	LXI	H,WRBUF
	CALL	ZERO		;ZERO WRITE BUFFER
	JMP	MLOOP		;EXECUTE TRANSLATION
	ENDIF
	IF	CPM
	LXI	H,FCB+1		;POINT TO FCB NAME AREA
	MOV	A,M		;GET FIRST CHARACTER
	CPI	' '		;SPACE?
	JNZ	GOTARG		;NO, HAVE ARGUMENT
	ENDIF
NOFILE	CALL	TYPTX
	DB	13,10,'ERROR - No source specified.',13,10+80H
	JMP	EXIT		;EXIT
	IF	CPM
GOTARG	DCX	H		;BACK UP TO FCB START
	LXI	D,OUTFCB	;POINT TO OUTPUT FCB
	MVI	B,9		;MOVE 9 CHARACTERS
MOVFCB	MOV	A,M		;MOVE THE CHARACTERS
	STAX	D
	INX	H
	INX	D
	DCR	B
	JNZ	MOVFCB
	LDA	FCB2		;GET OPTIONAL OUTPUT DRIVE
	ORA	A		;ANY SPECIFIED?
	JZ	NODRV		;NO
	STA	OUTFCB		;ELSE, PUT IN OUTPUT FCB
NODRV	LXI	H,FCB+9		;POINT TO EXTENSION AREA
	MOV	A,M
	CPI	' '		;NO EXTENSION?
	JNZ	GOTEXT		;EXTENSION THERE
	MVI	M,'X'		;ELSE, INSERT "XET"
	INX	H
	MVI	M,'E'
	INX	H
	MVI	M,'T'
GOTEXT	MVI	A,1AH
	MVI	B,128
	LXI	H,WRBUF
	CALL	FILL		;PRE-FILL WRITE BUFFER WITH EOF'S
	LXI	D,FCB
	MVI	C,OPENF
	CALL	BDOS		;TRY TO OPEN INPUT FILE
	INR	A		;GOOD OPEN?
	JNZ	GOODOP		;YES
	CALL	TYPTX
	DB	13,10,'ERROR - Input file cannot be found.',13,10+80H
	JMP	EXIT
GOODOP	LXI	D,OUTFCB
	MVI	C,OPENF
	CALL	BDOS		;TRY TO OPEN OUTPUT FILE
	INR	A
	JZ	MAKEIT		;NO FILE THERE, MAKE NEW
	LXI	D,OUTFCB
	MVI	C,DELETF
	CALL	BDOS		;DELETE FILE
MAKEIT	LXI	D,OUTFCB
	MVI	C,MAKEF
	CALL	BDOS		;MAKE OUTPUT FILE
	INR	A		;GOOD MAKE
	JNZ	MLOOP		;YES
	CALL	TYPTX
	DB	13,10,'ERROR - Directory full.',13,10+80H
	JMP	EXIT
	ENDIF

*	MAIN LOOP - TRANSLATE CODE

MLOOP	CALL	GETLIN		;GET LINE FROM INPUT
	JC	FINISH		;END OF FILE, FINISH UP
	LHLD	LINES
	INX	H		;COUNT THIS LINE
	SHLD	LINES
	LXI	H,INLIN		;POINT TO INPUT LINE
	LXI	D,OUTLIN	;AND OUTPUT LINE
	MOV	A,M		;GET FIRST CHARACTER
	CPI	';'		;COMMENT?
	JZ	MLOOP		;YES, GET NEXT LINE
	CALL	TESTC		;TEST CHARACTER
	JC	MLOOP		;CR, EMPTY LINE
	JZ	MLOOP1		;SPACE OR TAB, FIND ARGUMENT
	CALL	SKIPLAB		;SKIP LABEL AND PUT IT IN OUTPUT
	MOV	A,M		;GET NEXT CHARACTER
	IF	HDOS
	CPI	10		;EOL?
	ENDIF
	IF	CPM
	CPI	13		;CR?
	ENDIF
	JZ	MLOOP9		;YES, LINE COMPLETE
MLOOP1	CALL	SKIPTAB		;SKIP TAB AND PUT IT IN OUTPUT
	MOV	A,M		;GET NEXT CHARACTER
	IF	HDOS
	CPI	10		;EOL?
	ENDIF
	IF	CPM
	CPI	13		;CR?
	ENDIF
	JZ	MLOOP9		;YES, EMPTY LINE
	CPI	';'		;COMMENT?
	JZ	MLOOP9		;YES, EMPTY LINE
	PUSH	D		;SAVE OUTPUT POINTER
	LXI	D,OPCODE	;GET OPCODE BUFFER
	CALL	SKIPLAB		;PUT OPCODE IN BUFFER
	MOV	A,M		;GET NEXT CHARACTER
	IF	HDOS
	CPI	10		;EOL?
	ENDIF
	IF	CPM
	CPI	13		;CR?
	ENDIF
	JZ	MLOOP5		;YES, TRANSLATE OPCODE
MLOOP3	INX	H
	MOV	A,M
	CPI	' '		;SKIP OTHER TABS/SPACES
	JZ	MLOOP3
	CPI	9
	JZ	MLOOP3
	CPI	';'		;COMMENT?
	JZ	MLOOP5		;YES, TRANSLATE OPCODE
	CPI	'A'		;CHECK FOR A OR B (SPECIAL CASE
	JZ	MLOOP3A		;IT'S A
	CPI	'B'
	JNZ	MLOOP4		;NOT B
MLOOP3A	MOV	B,A		;SAVE A OR B
	INX	H
	MOV	A,M		;GET NEXT CHARACTER
	CALL	TESTC		;TEST IT
	DCX	H		;BACK UP TO A OR B
	JNZ	MLOOP4		;NOT CR OR SPACE OR TAB
	MVI	A,' '
	STAX	D		;PUT SPACE IN OPCODE
	INX	D
	MOV	A,B
	STAX	D		;STORE A OR B
	INX	D
	JC	MLOOP5		;CR, OPCODE COMPLETE
MLOOP3B	INX	H
	MOV	A,M
	CPI	' '		;SKIP ANY SPACES/TABS
	JZ	MLOOP3B
	CPI	9
	JZ	MLOOP3B
MLOOP4	CPI	';'		;COMMENT?
	JZ	MLOOP5		;YES, OPCODE COMPLETE
	MVI	A,9
	STAX	D		;PUT ONE TAB AFTER OPCODE
	INX	D
	CALL	SKIPARG		;PUT ARGUMENT IN BUFFER

*	AT THIS POINT, WE SHOULD HAVE THE OPCODE AND
*	TRANSLATED ARGUMENT IN THE BUFFER "OPCODE".
*	THE REAL ARGUMENT IS STORED AT "ARG" FOR LATER
*	INSERTION INTO THE OUTPUT LINE

MLOOP5	XRA	A
	STAX	D		;ZERO END OF OPCODE/ARGUMENT
	LXI	H,OPCODES	;POINT TO OPCODES
	LXI	D,OPCODE	;AND OUR OPCODE
	LXI	B,OPEND-OPCODES	;SEARCH THIS AREA
	CALL	COUNT		;COUNT CHARACTERS IN OPCODE
	CALL	SEARCH		;SEARCH FOR OPCODE
	JZ	MLOOP6		;FOUND IT
	CALL	PERROR		;PRINT ERROR LINE
	LHLD	PLINES
	INX	H		;COUNT PASSED LINES
	SHLD	PLINES
	LXI	H,INLIN		;POINT TO INPUT LINE
	POP	D		;FIX STACK
	LXI	D,OUTLIN	;POINT TO OUTPUT LINE
	JMP	MLOOP7		;PASS THE LINE UNCHANGED
MLOOP6	POP	D		;GET OUTPUT ADDRESS
	PUSH	H		;SAVE HL
	LHLD	XLINES
	INX	H		;COUNT TRANSLATED LINES
	SHLD	XLINES
	POP	H
MLOOP7	MOV	A,M		;GET A CHARACTER
	ORA	A		;END OF OPCODE?
	JZ	MLOOP9		;YES, FINISHED
	IF	HDOS
	CPI	10		;EOL?
	ENDIF
	IF	CPM
	CPI	13		;CR?
	ENDIF
	JZ	MLOOP9		;YES, FINISHED
	CPI	'@'		;DUMMY ARGUMENT?
	JNZ	MLOOP8		;NO
	CALL	INSARG		;ELSE, REPLACE WITH REAL ARGUMENT
	INX	H		;MOVE TO NEXT CHARACTER
	JMP	MLOOP7		;KEEP GOING
MLOOP8	STAX	D		;STORE CHARACTER
	INX	D		;INCREMENT POINTERS
	INX	H
	JMP	MLOOP7		;FINISH THE LINE
MLOOP9	DS	0
	IF	CPM
	MVI	A,13
	STAX	D		;PUT IN CR
	INX	D
	ENDIF
	MVI	A,10
	STAX	D		;AND LF
	CALL	PUTLIN		;OUTPUT COMPLETED LINE
	JMP	MLOOP		;GET ANOTHER LINE

*	FINISHED - FLUSH OUTPUT BUFFER AND CLOSE FILES

FINISH	DS	0
	IF	HDOS
	MVI	A,1
	LXI	B,100H
	LXI	D,WRBUF
	SCALL	.WRITE		;WRITE LAST BUFFER FULL
	JC	ERROR
	MVI	A,1
	SCALL	.CLOSE		;CLOSE OUTPUT FILE
	JC	ERROR
	XRA	A
	SCALL	.CLOSE		;CLOSE INPUT FILE
	JC	ERROR		;SHOULD NOT HAPPEN
	ENDIF
	IF	CPM
	LXI	D,WRBUF
	MVI	C,SETDMA
	CALL	BDOS		;SET DMA TO OUTPUT BUFFER
	LXI	D,OUTFCB
	MVI	C,WRITEF
	CALL	BDOS		;WRITE LAST BUFFER FULL
	ORA	A		;GOOD WRITE
	JNZ	WRERR		;NO
	LXI	D,OUTFCB
	MVI	C,CLOSEF	;ELSE, CLOSE OUTPUT FILE
	CALL	BDOS
	INR	A		;GOOD CLOSE?
	JZ	WRERR		;NO
	ENDIF
	CALL	TYPTX
	DB	13,10,'Cross assembly complete.',13,10+80H
	LHLD	LINES
	CALL	DECOUT		;PRINT LINES INPUT
	CALL	TYPTX
	DB	' Lines in source.',13,10+80H
	LHLD	XLINES
	CALL	DECOUT		;PRINT LINES TRANSLATED
	CALL	TYPTX
	DB	' Lines translated.',13,10+80H
	LHLD	PLINES
	CALL	DECOUT		;PRINT LINES PASSED
	CALL	TYPTX
	DB	' Lines passed unchanged.',13,10+80H
EXIT	DS	0
	IF	HDOS
	XRA	A
	SCALL	.EXIT		;RETURN TO HDOS
	ENDIF
	IF	CPM
	LHLD	OLDSP		;GET OLD STACK
	SPHL			;SET IT
	RET			;RETURN TO CP/M
	ENDIF

*	SUBROUTINES

*	GETLIN - GET A LINE FROM THE INPUT FILE

GETLIN	LXI	H,INLIN		;PUT LINE HERE
GETLIN1	CALL	RDCHR		;READ CHARACTER FROM FILE
	RC			;END OF FILE
	MOV	M,A		;STORE CHARACTER
	INX	H		;INCREMENT POINTER
	CPI	10		;END OF LINE?
	JNZ	GETLIN1		;NO, CONTINUE
	RET

*	PUTLIN - PUT A LINE IN THE OUTPUT FILE

PUTLIN	LXI	H,OUTLIN	;PUT LINE HERE
PUTLIN1	MOV	A,M		;GET A CHARACTER
	CALL	WRCHR		;WRITE IT OUT
	INX	H		;INCREMENT POINTER
	CPI	10		;END OF LINE?
	JNZ	PUTLIN1		;NO, CONTINUE
	RET

*	PERROR - PRINT LINE WITH ERROR

PERROR	PUSH	H		;SAVE HL
	LXI	H,INLIN		;INPUT LINE IS HERE
PERROR1	MOV	A,M		;GET A CHARACTER
	CALL	SCOUT		;PRINT IT
	CPI	10		;END OF LINE?
	JZ	PERROR2
	INX	H		;INCREMENT POINTER
	JMP	PERROR1		;DO IT ALL
PERROR2	POP	H		;RESTORE HL
	RET

*	RDCHR - READ A CHARACTER FROM THE INPUT FILE

RDCHR	PUSH	H		;SAVE HL
	LXI	H,RDBUF		;POINT TO READ BUFFER
	XCHG			;IN DE
	LHLD	RDPTR		;GET READ POINTER
	CALL	CPHD		;COMPARE HL TO DE
	JNZ	RDCHR2		;NOT EQUAL, GET CHARACTER FROM FILE
	LXI	B,1024		;READ 1K
	LXI	H,RDBUF		;PUT DATA HERE
	CALL	READFIL		;READ FROM FILE
	JNC	RDCHR1		;GOOD READ
	IF	HDOS
	MVI	M,0		;MARK END OF FILE
	CPI	1		;EOF?
	JNZ	ERROR
	ENDIF
	IF	CPM
	MVI	M,1AH		;MARK END
	ENDIF
RDCHR1	LXI	H,RDBUF		;POINT TO READ BUFFER
	SHLD	RDPTR		;SET UP READ POINTER
RDCHR2	MOV	B,M		;GET CHARACTER
	INX	H		;INCREMENT POINTER
	SHLD	RDPTR		;UPDATE IT
	XCHG			;POINTER TO DE
	LXI	H,RDBUFE	;POINT TO END OF BUFFER
	CALL	CPHD		;AT END?
	JNZ	RDCHR3		;NO
	LXI	H,RDBUF		;ELSE, RESET POINTER
	SHLD	RDPTR
RDCHR3	POP	H		;RESTORE HL
	MOV	A,B		;GET CHARACTER
	IF	HDOS
	ORA	A		;END?
	ENDIF
	IF	CPM
	CPI	1AH		;END?
	ENDIF
	JZ	RDCHR4		;YES
	ORA	A		;ELSE, CLEAR CARRY
	RET
RDCHR4	STC			;MARK END
	RET

*	WRCHR - WRITE CHARACTER TO FILE

WRCHR	PUSH	H		;SAVE HL
	PUSH	PSW		;SAVE CHARACTER TO WRITE
	LXI	H,WRBUFE	;GET END OF WRITE BUFFER
	XCHG			;IN DE
	LHLD	WRPTR		;GET WRITE POINTER
	CALL	CPHD		;TIME TO WRITE?
	JNZ	WRCHR1		;NO
	IF	HDOS
	MVI	A,1		;WRITE ON CHANNEL 1
	LXI	D,WRBUF		;WRITE DATA HERE
	LXI	B,100H		;WRITE 1 SECTOR
	SCALL	.WRITE		;WRITE THE SECTOR
	JC	ERROR
	MVI	B,0
	LXI	H,WRBUF
	CALL	ZERO		;CLEAR WRITE BUFFER
	ENDIF
	IF	CPM
	LXI	D,WRBUF		;POINT TO WRITE BUFFER
	MVI	C,SETDMA
	CALL	BDOS		;SET DMA HERE
	LXI	D,OUTFCB	;GET OUTPUT FCB
	MVI	C,WRITEF
	CALL	BDOS		;WRITE ONE RECORD
	ORA	A		;GOOD WRITE?
	JZ	WRCHR0		;YES
WRERR	CALL	TYPTX
	DB	13,10,'ERROR - Can''t write output.',13,10+80H
	JMP	EXIT
WRCHR0	MVI	A,1AH
	LXI	H,WRBUF
	MVI	B,128
	CALL	FILL		;FILL WRITE BUFFER WITH EOF'S
	ENDIF
	LXI	H,WRBUF
	SHLD	WRPTR		;SET WRITE POINTER
WRCHR1	POP	PSW		;GET CHARACTER TO WRITE
	PUSH	PSW		;SAVE AGAIN
	ANI	7FH		;STRIP HIGH BIT
	MOV	M,A		;PUT IT IN BUFFER
	INX	H		;INCREMENT POINTER
	SHLD	WRPTR		;SAVE IT
	POP	PSW		;RESTORE CHARACTER
	POP	H		;RESTORE HL
	RET

*	READFIL - READ DISK FILE

*	ENTRY:
*	HL = ADDRESS TO READ INTO
*	BC = NUMBER OF BYTES TO READ

*	EXIT:
*	CY = 1 IF END OR ERROR, AND
*	HL = NEXT FREE BYTE
*	BC = UNUSED BYTES (OR RECORDS)
	IF	CPM
READFIL	MOV	A,B		;CONVERT BYTES TO CP/M RECORDS
	ADD	A
	MOV	C,A
	MVI	A,0		;GET A ZERO
	RAL			;ADD CARRY FROM ABOVE
	MOV	B,A		;BC = CP/M RECORDS
	LXI	D,FCB		;(LEAVE OUT IF EXTERNAL FCB)
RFIL1	PUSH	B		;SAVE COUNT
	XCHG			;DE = ADDRESS
	MVI	C,SETDMA
	CALL	CBDOS		;SET DMA ADDRESS
	XCHG			;DE = FCB
	MVI	C,READF
	CALL	CBDOS		;READ A RECORD
	ORA	A		;OPERATION OK?
	JNZ	RFIL2		;NO, EXIT
	LXI	B,80H
	DAD	B		;UPDATE ADDRESS
	POP	B		;GET RECORED COUNT
	DCX	B		;DECREMENT IT
	MOV	A,B
	ORA	C		;TEST
	JNZ	RFIL1		;CONTINUE IF NOT DONE
	RET			;ELSE, RETURN
RFIL2	POP	B		;RESTORE COUNT
	STC			;MARK ERROR
	RET
	ENDIF
	IF	HDOS
READFIL	XCHG			;DE = ADDRESS TO READ OR WRITE
	XRA	A		;USE CHANNEL 0
	SCALL	.READ		;READ THE FILE
	XCHG			;HL = NEXT UNUSED ADDRESS
	RET
	ENDIF

*	SKIPLAB - SKIP OVER LABEL, PUTTING IT IN BUFFER

SKIPLAB	MOV	A,M		;GET A CHARACTER
	CALL	TESTC		;TEST FOR SPACE, TAB, OR CR
	RZ
	STAX	D		;STORE CHARACTER
	INX	D
	INX	H
	JMP	SKIPLAB		;DO MORE

*	SKIPTAB - SKIP TABS AND SPACES, PUTTING THEM IN BUFFER

SKIPTAB	MOV	A,M		;GET A CHARACTER
	CPI	' '		;SPACE?
	JZ	SKIPT1		;YES, SAVE IT
	CPI	9		;TAB?
	RNZ			;NO, RETURN
SKIPT1	STAX	D		;STORE CHARACTER
	INX	H
	INX	D
	JMP	SKIPTAB		;DO MORE

*	SKIPARG - SKIP OVER ARGUMENT IN INPUT, AND TRANLATE
*	IT INTO A FORM WHERE "@" REPLACES THE VARIABLE PART
*	OF THE ARGUMENT.

SKIPARG	MOV	A,M		;GET FIRST CHARACTER
	CPI	'#'		;IMMEDIATE MODE?
	JNZ	SKIPA1		;NO
	STAX	D		;STORE "#" AS IS
	INX	D
	INX	H		;SKIP OVER "#"
SKIPA1	MVI	A,'@'		;INSERT "@" IN BUFFER
	STAX	D
	INX	D
SKIPA2	PUSH	D		;SAVE OUTPUT BUFFER
	LXI	D,ARG		;PUT REAL ARGUMENT HERE
SKIPA3	MOV	A,M		;GET A CHARACTER
	CPI	'['		;BRACKET?
	CZ	SKIPA6		;YES, PROCESS IT
	CALL	TESTC		;TEST IT
	JZ	SKIPA4		;END OF ARGUMENT
	CPI	','		;COMMA?
	JZ	SKIPA4		;YES
	STAX	D		;ELSE, STORE CHARACTER
	INX	D
	INX	H		;INCREMENT POINTERS
	JMP	SKIPA3
SKIPA4	XCHG
	MVI	M,0		;TERMINATE ARGUMENT
	XCHG
	POP	D		;RESTORE OUTPUT BUFFER
	CPI	','		;ENDED WITH COMMA?
	JNZ	SKIPA5		;NO
	STAX	D		;ELSE, STORE COMMA
	INX	D
	INX	H		;GET CHARACTER AFTER COMMA
	MOV	A,M
