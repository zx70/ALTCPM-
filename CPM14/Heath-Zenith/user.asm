;;;     EQUATES
;***********************************************
USER	EQU	2800H		;START OF USER AREA
OFFSETU	EQU	5080H-USER	;TO ITS SYSGEN LOCATION
				;INITIAL I/O BYTE
DEFIOB	EQU	81H		;CON:=CRT:,LST:=LPT:, PUN:=RDR:=TTY:
IOBYT	EQU	4203H		;STORE IOBYT
;
;NOTE:  THE IOBYT IS EXAMINED BY THE DRIVERS EACH TIME
;INPUT OR OUTPUT IS DONE BY CONSOLE, LIST, PUNCH AND READER.
;ITS VALUE DETERMINES WHICH PHYSICAL DEVICE WILL BE USED
;AND IS INITIALLY SET AT COLD BOOT FROM IOBLOC.
;THE IOBYT MAY BE CHANGED WHILE CP/M IS RUNNING
;EITHER BY STAT.COM OR YOUR OWN USER PROGRAM
;TO REDIRECT I/O TO A DIFFERENT PHYSICAL DEVICE.
;CHANGE THE VALUE STORED IN IOBLOC (27F3H) IF YOU WISH
;TO SELECT DIFFERENT PHYSICAL DEVICES AT COLD BOOT TIME.
;
;***********************************************
;;;	MODE AREA
;***********************************************
;
	ORG	USER-20H
;THIS DATA AREA IS LOCATED HERE SO IT'S LOCATION CAN
;BE EASILY DETERMINED BY THE CONFIGURATION PROGRAM
;
DRVFLG	DB	1		;0 ==> 1 DRIVE, 1 ==> 3 DRIVES
INITFLG	DB	0		;IF ZERO, THIS BIOS HAS
				;NOT BEEN CONFIGURED
H85FLG	DB	4EH		;8251 MODE BYTE
				;(NO. OF STOP BITS)
CONTY	DB	0		;0 ==> CRT: ON H8-5
				;<> 0 ==> ON H8-4
STRATE	DB	15		;DRIVE STEP RATE, MSEC/2
				;(DEFAULT IS 30 MSEC)
;
H84PT1	DB	H84CRT		;PORT FOR H8-4 NO. 1 PORT
H84PT2	DB	H89TTY		;PORT FOR H8-4 NO. 2 PORT
H84PT3	DB	H84LPT		;PORT FOR H8-4 NO. 3 PORT
H84PT4	DB	H84RDP		;PORT FOR H8-4 NO. 4 PORT
;
CRTBAUD	DW	B2400
TTYBAUD	DW	B300
LPTBAUD	DW	B4800
RDPBAUD	DW	B4800
;
UCASE:	DB	0		;UPPER ONLY IF SET
NULLOC:	DB	0		;ALT CONS NULLS
IOBLOC:	DB	DEFIOB		;INITIAL IOBYTE
	DB	1
;
;END OF DATA TABLE
;
	DS	5
IFLAG:	DB	0		;0 IF COLD, 1 IF WARM
	DB	0
	DB	VERS/10+30H, VERS MOD 10+30H
MODE2:	DB	0		;MODE EXPANSION
MODE1:	DB	TRKRD+RAW	;SET MODE HERE
;	ALL MODE FUNCTIONS DONE IF BIT=1
CAUTO	EQU	1		;COLD AUTO
WAUTO	EQU	2		;WARM AUTO
EIBIT	EQU	10H		;SET INTS
RAW	EQU	40H		;READ AFTER WRT
;NOTE:	TRKRD BIT PERMANENTLY ENABLED IN RELEASE 3
TRKRD	EQU	80H		;FULL TRACK READ
;
;***********************************************
;;;	USER AREA
;***********************************************
;
;I/O PORT EQUATES FOR HEATH H-8/5 I/O CARD.
H85CRT	EQU	372Q		;CONSOLE PORT
H85TTY	EQU	374Q		;ALT CONSOLE PORT
H85CAS	EQU	370Q		;CASSETTE PORT
;
;I/O PORT EQUATES FOR HEATH H-8/4 I/O CARD.
H84CRT	EQU	350Q		;CONSOLE PORT
H84TTY	EQU	300Q		;ALT CONSOLE PORT
H84LPT	EQU	340Q		;LINE PRINTER PORT
H84RDP	EQU	320Q		;READERPUNCH PORT ON H8-4
;
;I/O PORT EQUATES FOR H89 COMPUTER AND H88-3 I/O CARD
H89CRT	EQU	350Q		;CONSOLE PORT ON H89
H89TTY	EQU	330Q		;ALT CONSOLE ON H88-3
H89LPT	EQU	340Q		;LINE PRINTER ON H88-3
H89RDP	EQU	320Q		;READERPUNCH (DTE) ON H88-3
;
;BAUD RATE DIVISORS FOR 8250'S
;
B75	EQU	1536		;A
B110	EQU	1047		;B
B134	EQU	857		;C
B150	EQU	192		;D
B300	EQU	384		;E
B600	EQU	192		;F
B1200	EQU	96		;G
B1800	EQU	72		;H
B2400	EQU	48		;I
B4800	EQU	24		;J
B9600	EQU	12		;K
B19200	EQU	6		;L
;
	ORG	USER
;;;	USER AREA JUMP TABLE
;IMPORTANT: THESE JUMPS MUST REMAIN HERE, IN SAME ORDER
;
VCINIT:	JMP	HCINIT		;DEVICE INITIALIZATION
VCONST:	JMP	HCONST		;CONSOLE STATUS JUMP
VCONIN:	JMP	HCONIN		;CONSOLE INPUT JUMP
VCONOUT:JMP	HCONOUT		;CONSOLE OUTPUT JUMP
VLIST:	JMP	HLIST		;LIST DEVICE JUMP
VPUNCH:	JMP	HPUNCH		;PUNCH DEVICE JUMP
VREADER:JMP	HREADER		;READER DEVICE JUMP
VPRST:	MVI A,0 ! RET		;PRINTER STATUS NOT IMPLEMENTED
	DB	0,0,0		;RESERVED
	DW	LASTU-USER	;LENGTH OF USER AREA
;
;INITIALIZE BOTH PORTS OF AN H8-5 CARD
;FIRST DO CONSOLE PORT
;
HCINIT:				;I/O INITIALIZATION
	DI			;NO INTERRUPTS DURING I/O INIT.
	MVI	A,15H
	OUT	H85CRT+1	;SEND DUMMY MODE BYTE
				;TO H8-5 CRT PORT
	MVI	A,40H		;8251 INTERNAL RESET COMMAND
	OUT	H85CRT+1	;ISSUE IT AS A COMMAND
	LDA	H85FLG		;GET 8251 INITIALIZATION DATA
				;(NO. STOP BITS)
	OUT	H85CRT+1	;MODE WORD
	MVI	A,15H		;ENABLE XMIT & REC WITH INT. OFF
	OUT	H85CRT+1	;COMMAND WORD
;
;NOW DO TAPE PORT ON H8-5 CARD
;
	MVI	A,15H
	OUT	H85CAS+1
	MVI	A,40H
	OUT	H85CAS+1
	MVI	A,4EH
	OUT	H85CAS+1
	MVI	A,15H
	OUT	H85CAS+1

;
;FIND OUT WHICH TYPE OF CARD THE CONSOLE IS ON
;
	IN	H84CRT+3	;READ LINE CNTL REG
	MOV	B,A		;SAVE IT
	CMA			;COMPLEMENT LCR DATA
	ANI	0BFH		;BUT DON'T SET BREAK BIT
	OUT	H84CRT+3	;WRITE IT BACK
	IN	H84CRT+3	;THEN READ IT AGAIN
	CMP	B		;IS IT SAME AS ORIG ?
	MVI	A,0FFH		;ASSUME IT'S NOT, E.G. H8-4
	JNZ	H84		;IT REALLY WAS AN H8-4
	XRA	A		;ELSE GET A ZERO ==> H8-5
H84	STA	CONTY		;AND SAVE THE CONSOLE TYPE
;
;NOW INITIALIZE FOUR 8250 PORTS ON AN H8-4 CARD
;
	LHLD	CRTBAUD		;PICK UP BAUD RATE IN H,L
	LDA	H84PT1		;GET PORT
	MOV	B,A		;IN REG. B
	CALL	IN8250		;DO THE INITIALIZATION
;
	LHLD	TTYBAUD
	LDA	H84PT2
	MOV	B,A
	STA	TTYIN+8
	STA	TTYOUT+9
	ADI	5
	STA	TTYSTAT+1
	STA	TTYIN+1
	STA	TTYOUT+1
	CALL	IN8250
;
	LHLD	LPTBAUD
	LDA	H84PT3
	MOV	B,A
	STA	LPTOUT+16
	ADI	5
	STA	LPTOUT+8
	INR	A
	STA	LPTOUT+1
	CALL	IN8250
;
	LHLD	RDPBAUD
	LDA	H84PT4
	MOV	B,A
	STA	RDPIN+8
	STA	RDPOUT+9
	ADI	5
	STA	RDPSTAT+1
	STA	RDPIN+1
	STA	RDPOUT+1
	CALL	IN8250
;
;SET UP THE IOBYT
;
	LDA	IOBLOC		;GET THE DEFAULT I/O BYTE
	STA	IOBYT		;AND SET IT UP
;
	MVI	A,32		;SET UP HANDSHAKING COUNT
	STA	HSCNT		;FOR DIABLO 1640
;
	RET
;
;***********************************************
;;;	LOGICAL DEVICE ROUTINES
;***********************************************
;
HCONST:
	;CONSOLE STATUS ROUTINE
	CALL	CONS		;GET PHYSICAL DEVICE STATUS
	ORA	A		;
	RZ			;IF CHAR NOT AVAILABLE
	MVI	A,0FFH		;ELSE SHOW CHAR AVAILABLE
	RET
;
CONS:
	;GET STATUS OF A PHYSICAL DEVICE
	LDA	IOBYT		;GET I/O ASSIGNMENT BYTE
	ANI	03H		;USE BITS 0-1 FOR CONSOLE
	RLC			;MULTIPLY BY TWO
	CALL	INDEX		;FIND ROUTINE ADDR & EXECUTE IT
	DW	TTYSTAT
	DW	CRTSTAT
	DW	RDRST		;"BATCH" MODE HANDLER
	DW	CRTSTAT		;UC1: = CRT: INPUT, LST: OUTPUT
;
RDRST:
	;READER STATUS ROUTINE FOR READER DEVICE & BATCH MODE
	LDA	IOBYT
	ANI	0CH		;MASK READER DEVICE BITS
	RRC			;SHIFT TO PROPER POSITION
	CALL	INDEX		;FIND ROUTINE & EXECUTE IT
	DW	TTYSTAT
	DW	CRTSTAT		;RDR:
	DW	HDUMMY		;UR1:
	DW	RDPSTAT		;UR2:
;
HCONIN:
	;MAIN CONSOLE INPUT ROUTINE
	CALL	CHIN
	;MAKE H8-5 CARD BACKSPACE WHEN RUBOUT SENT
	ANI	7FH		;STRIP PARITY
	STA	LASTIN		;SAVE FOR DELETE TEST
	RET
;
CHIN:
	;CONSOLE CHARACTER INPUT ROUTINE
	LDA	IOBYT		;GET I/O DEVICE ASSIGNMENT BYTE
	ANI	03H		;MASK CONSOLE BITS
	RLC			;SHIFT LEFT FOR INDEX
	CALL	INDEX
	DW	TTYIN
	DW	CRTIN
	DW	HREADER		;BATCH MODE READER
	DW	CRTIN		;UC1: = CRT: INPUT, LST: OUTPUT
;
HCONOUT:
	;CONSOLE CHARACTER OUTPUT ROUTINE
	MOV	A,C		;GET CHAR
	CPI	7FH		;WAS IT A DELETE ?
	RZ			;IGNORE PROCESSING THEN
	LDA	LASTIN		;GET LAST CHAR INPUT
	CPI	7FH		;WAS IT A DELETE ?
	JNZ	CHOUT		;NO
	MVI	C,8		;YES, SEND A BACKSPACE
	CALL	CHOUT		;
	MVI	C,' '		;FOLLOWED BY A SPACE
	CALL	CHOUT		;
	MVI	C,8		;FOLLOWED BY ANOTHER BACKSPACE
CHOUT:
	CALL	CASET		;CONVT TO UPPER CASE IF H9
	LDA	IOBYT
	ANI	03H		;MASK CONSOLE BITS
	RLC			;
	CALL	INDEX		;DISPATCH TO OUTPUT ROUTINE
	DW	TTYNULL
	DW	CRTOUT
	DW	HLIST
	DW	HLIST		;UC1: = CRT: INPUT, LST: OUTPUT
;
CASET:	LDA	UCASE		;CONVT TO UC IF H9 TERMINAL
	ORA	A		;NO LC IF =1
	RZ			;LOWER ALLOWED
	MOV	A,C		;GET CHAR
	CPI	60H
	RC			;FILTER BELOW 60H
	CPI	7BH
	RNC			;FILTER ABOVE 'z'
	ANI	5FH		;CONVT TO UPPER CASE
	MOV	C,A		;AND BACK TO C
	RET
;
HLIST:
	;LIST OUTPUT ROUTINE
	LDA	IOBYT		;GET I/O ASSIGNMENT BYTE
	ANI	0C0H		;MASK BITS
	RLC
	RLC
	RLC			;NOW SET UP FOR INDEX
	CALL	INDEX		;EXECUTE LIST OUTPUT ROUTINE
	DW	TTYNULL		;TTY:=LA-36
	DW	CRTOUT
	DW	LPTOUT		;LPT:=H-14 OR TI810
	DW	DIABOUT		;UL1:= DIABLO AT 1200 BUAD
;
HPUNCH:
	;PUNCH OUTPUT ROUTINE
	LDA	IOBYT
	ANI	30H		;MASK PUNCH BITS
	RRC
	RRC
	RRC			;SET UP FOR INDEX
	CALL	INDEX
	DW	TTYOUT
	DW	CRTOUT		;PTP:
	DW	HDUMMY		;UP1:
	DW	RDPOUT		;UP2:
;
HREADER:
	;READER INPUT ROUTINE
	LDA	IOBYT
	ANI	0CH
	RRC
	CALL	INDEX
	DW	TTYIN
	DW	CRTIN		;PTR:
	DW	HDUMMY		;UR1:
	DW	RDPIN		;UR2:
;
HDUMMY:
	;DUMMY FOR NON-IMPLEMENTED DEVICES
	MVI	A,1AH	;RETURN A CP/M EOF MARK
	RET
;
;SUBROUTINE TO INDEX INTO A TABLE FOLLOWING THE CALL
;BASED ON VALUE IN BITS 1-2 (STARTING WITH LSB=0) OF
;ACCUMULATOR
;
;RETURNS TO ROUTINE CALLING ROUTINE WHICH CALLED THIS ROUTINE
;
INDEX:	XTHL			;H,L=TABLE ADDR
	PUSH	D		;SAVE REGS
	MOV	E,A		;SETTING UP D,E AS INDEX
	MVI	D,0
	DAD	D		;H,L HAS ROUTINE ADDR
	MOV	A,M		;GET ADDR LOW ORDER BYTE
	INX	H		;POINT TO HIGH ORDER BYTE
	MOV	H,M		;
	MOV	L,A		;H,L HAS ROUTINE ADDR
	POP	D		;RESTORE D,E
	XTHL			;STACK = ROUTINE, H,L = ORIG H,L
	RET			;EXECUTE THE ROUTINE & RET
;
;
;***********************************************
;;;	PHYSICAL DEVICE ROUTINES
;***********************************************
;
;
;ROUTINE TO INITIALIZE ONE PORT OF AN 8250 ON AN H8-4 CARD
;REG. H,L HAS BAUD RATE WORD
;REG B HAS BASE PORT
;
IN8250	XCHG			;MOVE BAUD RATE TO D,E
	LXI	H,OUTH84+1	;POINT TO PORT IN OUT INST
	MVI	A,3		;BAUD RATE ACCESS BIT
				;ON BASE+3 PORT
	ADD	B		;GET ACTUAL PORT
	MOV	C,A		;SAVE IN C FOR LATER
	MOV	M,A		;AND MODIFY OUTPUT INST
	MVI	A,83H		;SET DIVISOR LATCH ACCESS BIT
	CALL	OUTH84		;TO A "1"
	INR	M		;POINT TO MODEM CNTL REG
	MVI	A,3		;AND SET DSR AND CTS HIGH
	CALL	OUTH84		;FOR DIABLO & OTHER TERM
	MOV	M,B		;SET PORT TO LEAST SIG BYTE
	MOV	A,E		;GET LEAST SIG BAUD RATE
	CALL	OUTH84		;AND OUTPUT
	MOV	A,D		;NOW DO MOST SIG BYTE
	ANI	7FH		;CLEAR STOP BIT BIT
	INR	M		;ONE NEXT PORT
	CALL	OUTH84		;
	MOV	M,C		;RESET PORT TO DIVISOR LATCH
	MOV	A,D		;SEE HOW MANY STOP BITS
	ANI	80H		;HIGH BIT ==> NR STOP BITS
	MVI	A,3		;8 DATA BITS, NO PARITY
	JNZ	IN82501		;WITH 1 STOP BIT
	MVI	A,7		;USE 2 STOP BITS
IN82501	CALL	OUTH84		;SET UP LINE CTL REG
	DCR	M		;NOW SET PORT
	DCR	M		;TO INT ENABLE REG
	XRA	A		;TURN OFF INTERRUPTS
	CALL	OUTH84		;AT INT ENABLE REG
;
;THE FOLLOWING CODE USES THE BAUD RATE DIVISOR TO
;DO A TWO CHARACTER TIMES DELAY BEFORE RETURNING
;
	XCHG			;PUT BAUD RATE DIVISOR IN HL
	DAD	H		;MULTIPLY BY 16 TO GET DELAY
	DAD	H
	DAD	H
	DAD	H
LOOP1	DCX	H		;
	MOV	A,L		;
	ORA	H		;
	JNZ	LOOP1
	RET			;DONE
;
;FOLLOWING IS THE OUTPUT INSTRUCTION EXECUTED BY IN8250
;THE PORT IS MODIFIED BY THE CODE BEFORE THE ROUTINE IS CALLED
;IT IS ALSO USED BY SOME OTHER H8-4 ROUTINES
;
OUTH84	OUT	0		;PORT GETS MODIFIED BY ABOVE CODE
	RET			;
;
;AND A VARIABLE INPUT INST
;
INH84	IN	0
	RET
;
;"CRT" PHYSICAL STATUS ROUTINE
;
CRTSTAT	LDA	CONTY		;GET CONSOLE TYPE
	ORA	A		;SET FLAGS
	JZ	H85STAT		;CRT IS ON H8-5 CARD
;
H84STAT	IN	H84CRT+5	;GET STATUS
	ANI	1		;MASK DATA AVAIL BIT
	RET
;
H85STAT	IN	H85CRT+1	;GET STATUS
	ANI	2		;MASK DATA AVAIL BIT
	RET
;
;"CRT" PHYSICAL INPUT ROUTINE
;
CRTIN	LDA	CONTY
	ORA	A		;SET FLAGS
	JZ	CRTH85		;"CRT" IS ON H8-5 CARD
;
CRTH84	IN	H84CRT+5	;GET STATUS
	ANI	1
	JZ	CRTH84
	IN	H84CRT		;GET DATA
	RET
;
CRTH85	IN	H85CRT+1	;GET STATUS
	ANI	2		;MASK DATA AVAIL BIT
	JZ	CRTH85		;WAIT FOR CHAR
	IN	H85CRT		;GET DATA
	RET
;
;"CRT" PHYSICAL OUTPUT ROUTINE
;
CRTOUT	LDA	CONTY
	ORA	A
	JZ	H85OUT
;
H84OUT	IN	H84CRT+5	;GET STATUS
	ANI	20H		;MASK HOLDING REG. EMPTY BIT
	JZ	H84OUT		;REG NOT EMPTY
	MOV	A,C		;GET CHAR
	OUT	H84CRT		;WRITE CHAR
	RET
;
H85OUT	IN	H85CRT+1	;GET STATUS
	ANI	1		;TXRDY CHAR TO CARRY FLAG
	JZ	H85OUT		;WAIT TILL READY
	MOV	A,C		;GET CHAR
	OUT	H85CRT		;WRITE IT
	RET
;
;"TTY" PHYSICAL ROUTINES
;
TTYSTAT	IN	H84TTY+5	;GET STAT
	ANI	1		;MASK REC. DATA AVAIL BIT
	RET
;
;"TTY" INPUT ROUTINE
;
TTYIN	IN	H84TTY+5	;GET STATUS
	ANI	1
	JZ	TTYIN
	IN	H84TTY
	RET
;
;"TTY" OUTPUT ROUTINES
;
TTYOUT	IN	H84TTY+5
	ANI	20H
	JZ	TTYOUT
	MOV	A,C
	OUT	H84TTY
	RET
;
;TTY (ALT CON) PATCH TO ALLOW NULLS AFTER CARRIGE RETURN
;
TTYNULL:
	CALL	TTYOUT		;SEND THE CHARACTER
	MOV	A,C		;WAS IT A
	CPI	0DH		;CARRIGE RETURN?
	RNZ			;FINISHED IF NOT
	LDA	NULLOC		;GET PROPER NR OF NULLS
	ORA	A		;TEST FOR ZERO
	RZ			;AND RETURN IF NULLS=0
	MOV	B,A		;AND MOVE INTO B REG
	MVI	C,0		;THIS IS A NULL
TTYLP:	CALL	TTYOUT		;SEND ONE NULL
	DCR	B		;COUNT DOWN
	JNZ	TTYLP		;MORE NULLS UNTIL B=0
	MVI	C,0DH		;RESTORE ORIG TO C REG
	RET			;AND RETURN
;
;"DIAB" (1200 BAUD DIABLO) OUTPUT ROUTINE
;
DIABOUT:
	CALL	TTYOUT		;SEND THE CHAR IN C
	LXI	H,HSCNT		;PT TO HANDSHAKING COUNT AND
	DCR	M		;DECR CNT OF CHARS TO SEND
	JM	DIAB0
	RNZ			;AT LEAST 2 MORE CHARS WILL BE SENT
DIAB0:	CPI	1BH		;WAS CHAR AN ESC?
	JNZ	DIAB1		;NO, NORMAL CHAR
	MVI	M,1		;INSURE 2 MORE CHARS WILL BE SENT
	RET			;AND RET
DIAB1:	MOV	A,M		;GET COUNT
	ORA	A
	RP			;IF GT ZERO
	MVI	C,'C'-40H	;GET AN ETX
	CALL	TTYOUT
DIAB2:	CALL	TTYIN		;NOW WAIT FOR ACK
	CPI	'F'-40H		;ACK?
	JNZ	DIAB2		;NO, WAIT SOME MORE
	MVI	M,32		;YES, RESET HAND SHAKE CNT
	RET
HSCNT:	DB	32		;HANDSHAKING COUNT
;
;"LPT" (H14) OUTPUT ROUTINE
;
LPTOUT	IN	H84LPT+6	;GET 8250 MODEM STATUS
	ANI	10H		;MASK CLEAR TO SEND BIT
	JNZ	LPTOUT		;WAIT FOR H14 TO BECOME READY
	IN	H84LPT+5	;NOW SEE IF 8250 IS READY
	ANI	20H		;MASK HOLD REG EMPTY BIT
	JZ	LPTOUT		;AND WAIT IF IT'S NOT READY
	MOV	A,C		;BOTH 8250 AND H-14 ARE READY
	OUT	H84LPT
	RET
;
;"READERPUNCH" PHYSICAL ROUTINES
;
RDPSTAT	IN	H84RDP+5	;GET STAT
	ANI	1		;MASK REC. DATA AVAIL BIT
	RET
;
;"READERPUNCH" INPUT ROUTINE
;
RDPIN	IN	H84RDP+5	;GET STATUS
	ANI	1
	JZ	RDPIN
	IN	H84RDP
	RET
;
;"READERPUNCH" OUTPUT ROUTINES
;
RDPOUT	IN	H84RDP+5
	ANI	20H
	JZ	RDPOUT
	MOV	A,C
	OUT	H84RDP
	RET
LASTIN:	DB	0		;LAST CHAR INPUT FROM CONSOLE
LASTU	EQU	$		;END OF USER AREA
;
